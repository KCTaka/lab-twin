#!/usr/bin/env python3
"""Write docs/STATUS.md: pipeline state per active asset + the measurement checklist.

The checklist lists every parameter still `assumed`, i.e. exactly what a person
with a tape measure (or a vendor e-mail) must resolve to make assets non-provisional.
"""
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ASSETS, ROOT, STAGES, load_spec, provisional_params, read_manifest, spec_path  # noqa: E402

rows = [r for r in read_manifest() if not r["s2_source"].startswith("skip")]
out = ["# Pipeline status", "", "Generated by `pipeline/report.py`; do not edit by hand.", "",
       "| asset | family | qty | " + " | ".join(STAGES) + " |", "|---|---|---|" + "---|" * len(STAGES)]
for r in rows:
    out.append(f"| `{r['asset_id']}` | {r['family']} | {r['instances']} | " + " | ".join(r[s] for s in STAGES) + " |")
out += ["", "## Scope counts (whole inventory)", ""]
for k, v in sorted(Counter(r["scope"] for r in read_manifest()).items()):
    out.append(f"- {k}: {v}")
out += ["", "## Measurement checklist", "",
        "Values below are `assumed`. Measure (record `src: measured`, `by`, `date`) or cite a datasheet, then re-run `pipeline/run_batch.sh`.", ""]
for r in rows:
    if not spec_path(r["asset_id"]).exists():
        continue
    spec = load_spec(r["asset_id"])
    prov = provisional_params(spec)
    if not prov:
        continue
    out.append(f"### {spec['inventory']['manufacturer']} {spec['inventory']['part_number']}  (`{r['asset_id']}`, owned: {r['instances']})")
    for k in prov:
        if k == "physics.mass_kg":
            out.append(f"- [ ] mass (kg): {spec['physics']['mass_kg'].get('note', '')}")
        else:
            p = spec["params"][k]
            out.append(f"- [ ] `{k}` = {p['value']} mm (assumed): {p.get('note', '')}")
    if spec.get("notes"):
        out.append(f"- note: {spec['notes']}")
    out.append("")
(ROOT / "docs" / "STATUS.md").write_text("\n".join(out) + "\n")
print("REPORT docs/STATUS.md")
